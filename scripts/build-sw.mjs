// Runs after `next build`: writes out/sw.js, a service worker that caches every
// file of the static build so the app opens and works with no internet.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(OUT)
  .map((p) => relative(OUT, p).split(sep).join("/"))
  .filter((f) => f !== "sw.js" && f !== "404.html" && !f.startsWith("404/") && !f.endsWith(".map"))
  .sort();

const hash = createHash("sha1");
for (const f of files) hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);

// "daftar/index.html" is served at "daftar/", so cache it under that URL too.
const urls = files.flatMap((f) => {
  const url = `${base}/${f}`;
  if (f === "index.html") return [`${base}/`, url];
  if (f.endsWith("/index.html")) return [`${base}/${f.slice(0, -"index.html".length)}`, url];
  return [url];
});

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = "rumahlist-${version}";
const BASE = ${JSON.stringify(base)};
const URLS = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("rumahlist-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

async function fromCache(request) {
  const cache = await caches.open(CACHE);
  const url = new URL(request.url);
  let hit = await cache.match(request, { ignoreSearch: true });
  if (hit) return hit;
  if (request.mode === "navigate") {
    const path = url.pathname.endsWith("/") ? url.pathname : url.pathname + "/";
    hit = (await cache.match(path)) || (await cache.match(BASE + "/"));
  }
  return hit;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  // Cache first: the whole app is pre-cached, and a new build ships a new cache.
  event.respondWith(fromCache(request).then((hit) => hit || fetch(request)));
});
`;

writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} URLs cached as rumahlist-${version}`);
